// Builds the app icons, splash image and in-app logo from the brand SVGs in design/logo/.
//
//   node scripts/build_logo.mjs
//
// Inputs (made by scripts/split_logo.cjs from design/logo/source/, the files from "Logo Versions/01"):
//   design/logo/emblem.svg     sun emblem, original colour, transparent
//   design/logo/lockup.svg     primary lockup (emblem + "Ameesi"), original colour, transparent
//   design/logo/sun-gold.svg   small icon: central sun only, gold, transparent
//   design/logo/sun-white.svg  small icon: central sun only, white, transparent (Android themed icon)
//
// Outputs: assets/icon.png, assets/android-icon-{foreground,background,monochrome}.png,
// assets/splash-icon.png, assets/favicon.png, src/generated/logo.ts (SVG text for SvgXml).
// Rendering uses Playwright's Chromium (a development tool, not an app dependency).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const { chromium } = require("playwright");

const app = join(dirname(fileURLToPath(import.meta.url)), "..");
const logoDir = join(app, "..", "design", "logo");
const tokens = JSON.parse(readFileSync(join(app, "..", "design", "tokens.json"), "utf8"));
// The icon sits on the logo's own midnight; fall back to the app background.
const MIDNIGHT = tokens.color.tokens.find((t) => t.name === "logo-midnight").value;

const svg = (name) => readFileSync(join(logoDir, `${name}.svg`), "utf8");

/** Render an SVG centred on a square canvas. `scale` is the share of the canvas the artwork's longer side takes. */
async function render(page, { svgText, size, scale, background, out }) {
  const inner = Math.round(size * scale);
  await page.setViewportSize({ width: size, height: size });
  await page.setContent(`<!doctype html><html><body style="margin:0;width:${size}px;height:${size}px;display:flex;
    align-items:center;justify-content:center;background:${background ?? "transparent"}">
    <div style="width:${inner}px;height:${inner}px;display:flex;align-items:center;justify-content:center">${svgText}</div>
    <style>svg{max-width:100%;max-height:100%;width:100%;height:100%}</style></body></html>`);
  await page.screenshot({ path: join(app, "assets", out), omitBackground: !background });
  console.log("wrote", out);
}

const browser = await chromium.launch();
const page = await browser.newPage();
const emblem = svg("emblem"), lockup = svg("lockup"), sunGold = svg("sun-gold"), sunWhite = svg("sun-white");

// Store icon: emblem on midnight, with breathing room.
await render(page, { svgText: emblem, size: 1024, scale: 0.82, background: MIDNIGHT, out: "icon.png" });
// Android adaptive icon: launchers crop to a circle or squircle; the safe zone is the middle 66%.
await render(page, { svgText: emblem, size: 1024, scale: 0.66, out: "android-icon-foreground.png" });
await render(page, { svgText: "", size: 1024, scale: 1, background: MIDNIGHT, out: "android-icon-background.png" });
// Themed (monochrome) icon: the sun alone, which reads at small sizes.
await render(page, { svgText: sunWhite, size: 1024, scale: 0.5, out: "android-icon-monochrome.png" });
// Splash: the full lockup on a transparent square (the background colour comes from app.json).
await render(page, { svgText: lockup, size: 1024, scale: 0.9, out: "splash-icon.png" });
// Favicon: the sun alone.
await render(page, { svgText: sunGold, size: 48, scale: 0.92, out: "favicon.png" });
await browser.close();

const clean = (s) => s.replace(/<\?xml[^>]*>/g, "").replace(/<!--[\s\S]*?-->/g, "").replace(/\s+/g, " ").trim();
writeFileSync(join(app, "src", "generated", "logo.ts"),
  "// Generated by scripts/build_logo.mjs from design/logo/*.svg. Don't edit by hand.\n"
  + `export const emblemSvg = ${JSON.stringify(clean(emblem))};\n`
  + `export const lockupSvg = ${JSON.stringify(clean(lockup))};\n`
  + `export const sunSvg = ${JSON.stringify(clean(sunGold))};\n`);
console.log("wrote src/generated/logo.ts");
