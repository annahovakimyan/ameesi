// Generates src/generated/{tokens,glossary}.ts from design/tokens.json and content/glossary.json.
// Run `npm run generate` after either file changes. A test fails if the output is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const HEADER = "// GENERATED by app/scripts/generate.mjs. Do not edit; run `npm run generate`.\n\n";
const px = (v) => Number(String(v).replace("px", ""));

export function tokensSource() {
  const t = JSON.parse(readFileSync(join(root, "design", "tokens.json"), "utf8"));
  const colors = Object.fromEntries(t.color.tokens.map((c) => [camel(c.name), c.value]));
  const type = {};
  for (const group of t.type.groups) {
    for (const s of group.styles) {
      const style = { fontSize: px(s.fontSize), lineHeight: px(s.lineHeight), fontWeight: String(s.fontWeight) };
      if (s.letterSpacing) style.letterSpacing = Number((parseFloat(s.letterSpacing) * px(s.fontSize)).toFixed(2));
      type[camel(s.name)] = { ...style, family: group.family };
    }
  }
  const space = Object.fromEntries(t.spacing.tokens.map((s) => [Number(s.name.split("-")[1]), px(s.value)]));
  const radius = Object.fromEntries(t.radius.tokens.map((r) => [r.name.replace("radius-", ""), px(r.value)]));
  const stroke = Object.fromEntries(t.stroke.tokens.filter((s) => s.name.startsWith("stroke-"))
    .map((s) => [camel(s.name.replace("stroke-", "")), px(s.value)]));
  // "0 -8px 32px rgba(0, 0, 0, 0.45)" → offset, blur and colour, which React Native draws itself.
  const shadow = Object.fromEntries(t.shadow.tokens.filter((s) => s.name.startsWith("shadow-")).map((s) => {
    const m = s.value.match(/^(-?\d+)(?:px)?\s+(-?\d+)(?:px)?\s+(\d+)(?:px)?\s+(rgba?\([^)]*\))$/);
    if (!m) throw new Error(`unparsed shadow token ${s.name}: ${s.value}`);
    return [camel(s.name.replace("shadow-", "")), { x: Number(m[1]), y: Number(m[2]), blur: Number(m[3]), color: m[4] }];
  }));
  const dash = Object.fromEntries(t.stroke.tokens.filter((s) => s.name.startsWith("dash-"))
    .map((s) => [camel(s.name.replace("dash-", "")), s.value]));
  return HEADER +
    `export const colors = ${JSON.stringify(colors, null, 2)} as const;\n\n` +
    `export const type = ${JSON.stringify(type, null, 2)} as const;\n\n` +
    `export const space = ${JSON.stringify(space, null, 2)} as const;\n\n` +
    `export const radius = ${JSON.stringify(radius, null, 2)} as const;\n\n` +
    `export const stroke = ${JSON.stringify(stroke, null, 2)} as const;\n\n` +
    `export const dash = ${JSON.stringify(dash, null, 2)} as const;\n\n` +
    `export const shadow = ${JSON.stringify(shadow, null, 2)} as const;\n`;
}

const ANGLES = { Ascendant: "asc", Midheaven: "mc", Descendant: "dsc", "Imum Coeli (IC)": "ic" };
const NAMESPACE = {
  "Planets and celestial bodies": "body",
  "Zodiac signs": "sign",
  "Astrological houses": "house",
  "Astrological aspects": "aspect",
  "Chart angles": "angle",
  "Category names": "category",
};

function camel(s) {
  return s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
}

function termId(entry) {
  const slug = entry.en.toLowerCase().replace(/\s*\(.*\)/, "").trim().replace(/\s+/g, "_");
  if (entry.category === "Chart angles") return `angle.${ANGLES[entry.en]}`;
  if (entry.category === "Astrological houses") return `house.${parseInt(entry.en, 10)}`;
  if (entry.category === "Elements and modalities") {
    const kind = ["fire", "earth", "air", "water"].includes(slug) ? "element"
      : ["cardinal", "fixed", "mutable"].includes(slug) ? "modality" : "concept";
    return `${kind}.${slug}`;
  }
  if (entry.category === "Additional astrological concepts") {
    return ["north_node", "south_node", "chiron"].includes(slug) ? `body.${slug}` : `concept.${slug}`;
  }
  return NAMESPACE[entry.category] ? `${NAMESPACE[entry.category]}.${slug}` : null;
}

export function glossarySource() {
  const g = JSON.parse(readFileSync(join(root, "content", "glossary.json"), "utf8"));
  const terms = {};
  for (const entry of g) {
    const id = termId(entry); // "Combined terminology examples" are examples only: skipped
    if (!id) continue;
    if (terms[id]) throw new Error(`duplicate glossary id ${id}`);
    // Labels use `short` where the glossary gives one (e.g. without a gloss in brackets).
    const short = { hy: entry.hy, en: entry.en, ru: entry.ru, ...(entry.short ?? {}) };
    terms[id] = { hy: entry.hy, en: entry.en, ru: entry.ru, short, status: entry.status };
  }
  return HEADER + `export const terms = ${JSON.stringify(terms, null, 2)} as const;\n\n` +
    "export type TermId = keyof typeof terms;\n";
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = join(root, "app", "src", "generated");
  const files = { "tokens.ts": tokensSource(), "glossary.ts": glossarySource() };
  if (process.argv.includes("--check")) {
    const stale = Object.keys(files).filter((f) => readFileSync(join(out, f), "utf8") !== files[f]);
    if (stale.length) {
      console.error(`out of date: ${stale.join(", ")}. Run npm run generate.`);
      process.exit(1);
    }
  } else {
    for (const [f, src] of Object.entries(files)) writeFileSync(join(out, f), src);
    console.log("generated src/generated/tokens.ts and src/generated/glossary.ts");
  }
}
